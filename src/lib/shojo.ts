export function getShojo(slug: string): Shojo | undefined {
  return SHOJO.find(s => s.slug === slug)
}

// 盆栽用と分かるもの・写真のきれいなもの・レビューの多いものを先に
const score = (p: CatalogProduct) =>
  (hasCuratedImage(p) ? 4 : 0) + (/盆栽/.test(p.originalName) ? 2 : 0) - (/観葉|バラ|多肉|サボテン|野菜|家庭菜園|草花/.test(p.originalName) ? 3 : 0)

export function shojoProducts(shojo: Shojo, products: CatalogProduct[], perNeed = 3) {
  const used = new Set<string>()
  return (shojo.products ?? [])
    .map(need => {
      const list = products
        .filter(p => p.productType === need.type && need.pattern.test(p.originalName) && !(need.exclude && need.exclude.test(p.originalName)) && !used.has(p.id))
        .sort((a, b) => score(b) - score(a) || b.reviewCount - a.reviewCount)
        .slice(0, perNeed)
      list.forEach(p => used.add(p.id))
      return { label: need.label, note: need.note, products: list }
    })
    .filter(group => group.products.length > 0)
}
